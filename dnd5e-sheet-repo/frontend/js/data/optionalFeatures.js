export function optionalFeaturesAt(classId, level) {
  return (OPTIONAL_CLASS_FEATURES[classId] || []).filter((o) => o.level === level);
}
export function optionalReplaces(opt, featureName) {
  return (opt.replaces || []).some((re) => new RegExp(re, "i").test(featureName || ""));
}
